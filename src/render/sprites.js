const pixelArt={};


function makePixel(name,w,h,paint){
  const c=document.createElement('canvas');
  c.width=w;
  c.height=h;
  const x=c.getContext('2d');
  x.imageSmoothingEnabled=false;
  const r=(a,b,w,h,col)=>{
    x.fillStyle=col;
    x.fillRect(a,b,w,h)
  };
  const poly=(pts,col)=>{
    x.fillStyle=col;
    x.beginPath();
    pts.forEach(([a,b],i)=>i?x.lineTo(a,b):x.moveTo(a,b));
    x.closePath();
    x.fill()
  };
  paint(r,poly);
  pixelArt[name]=c;
}

